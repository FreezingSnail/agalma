//! Workspace provider-config lease (`agalma-crl`, `agalma-22f`).
//!
//! Paid mode must write `<workspace>/opencode.json`: OpenCode reads its global
//! config from `OPENCODE_CONFIG_DIR`, which the adapter points at the workspace
//! (see `spawn_server`). That file points a provider at a loopback proxy that
//! dies with the conductor, so an override that outlives its attempt breaks
//! every later OpenCode session in the workspace.
//!
//! A lease makes the override recoverable without guessing. Before writing, a
//! sidecar record (`opencode.json.agalma-lease`) captures the owning process,
//! the exact generated bytes, and the file it replaced. Restoration happens only
//! when the current file is byte-identical to what the lease generated, so a
//! user's own config — even one that also points at `127.0.0.1` — is never
//! mistaken for Agalma's. A record whose owner is dead is stale and is restored
//! by the next launch in that workspace; a live owner means another attempt is
//! using the workspace, which is a conflict.

use std::fs;
use std::io::ErrorKind;
use std::path::{Path, PathBuf};
use std::process::Command;

use agalma_contracts::error::ContractError;
use serde_json::{json, Value};

/// Provider config file OpenCode loads from `OPENCODE_CONFIG_DIR`.
pub(crate) const CONFIG_FILE: &str = "opencode.json";
/// Sidecar lease record next to [`CONFIG_FILE`].
pub(crate) const LEASE_FILE: &str = "opencode.json.agalma-lease";

/// An active override owned by this process. [`ProviderLease::release`]
/// restores the workspace; dropping the value without releasing leaves the
/// record for [`reconcile`] to recover once this process is gone.
#[derive(Debug)]
pub(crate) struct ProviderLease {
    workspace: PathBuf,
    generated: String,
}

/// The persisted lease record.
struct Record {
    owner_pid: u32,
    generated: String,
    previous: Option<String>,
}

/// Write `generated` as the workspace provider config under a lease.
///
/// Recovers any stale lease first and refuses (`Conflict`) when a live process
/// already holds one. The record is durable before the config is written, so a
/// crash between the two leaves a record whose generated bytes do not match the
/// file, which [`reconcile`] then drops without touching the user's config.
pub(crate) fn acquire(workspace: &Path, generated: String) -> Result<ProviderLease, ContractError> {
    reconcile(workspace)?;
    let config = workspace.join(CONFIG_FILE);
    let previous = match fs::read(&config) {
        Ok(bytes) => Some(String::from_utf8(bytes).map_err(|_| {
            ContractError::KnownFailure(format!(
                "{} is not UTF-8; refusing to override it",
                config.display()
            ))
        })?),
        Err(err) if err.kind() == ErrorKind::NotFound => None,
        Err(err) => {
            return Err(ContractError::KnownFailure(format!(
                "read {}: {err}",
                config.display()
            )))
        }
    };
    write_record(
        workspace,
        &Record {
            owner_pid: std::process::id(),
            generated: generated.clone(),
            previous,
        },
    )?;
    if let Err(err) = fs::write(&config, &generated) {
        let _ = fs::remove_file(workspace.join(LEASE_FILE));
        return Err(ContractError::KnownFailure(format!(
            "write provider config {}: {err}",
            config.display()
        )));
    }
    exclude_locally(workspace, &[CONFIG_FILE, LEASE_FILE]);
    Ok(ProviderLease {
        workspace: workspace.to_path_buf(),
        generated,
    })
}

impl ProviderLease {
    /// Restore the workspace to its pre-lease state (best-effort).
    ///
    /// Only this lease's own record is honoured: if the record now names another
    /// owner or different bytes, a later attempt took over and owns cleanup.
    pub(crate) fn release(self) {
        let Some(record) = read_record(&self.workspace) else {
            return;
        };
        if record.owner_pid == std::process::id() && record.generated == self.generated {
            restore(&self.workspace, &record);
        }
    }
}

/// Recover a stale lease in `workspace`.
///
/// Returns `true` when a stale lease (dead owner) was restored. A malformed
/// record is dropped without touching the config. A record owned by a live
/// process — including this one — is a `Conflict`: two attempts sharing one
/// workspace's provider config would clobber each other.
pub(crate) fn reconcile(workspace: &Path) -> Result<bool, ContractError> {
    let path = workspace.join(LEASE_FILE);
    if !path.exists() {
        return Ok(false);
    }
    let Some(record) = read_record(workspace) else {
        let _ = fs::remove_file(&path);
        return Ok(false);
    };
    if pid_alive(record.owner_pid) {
        return Err(ContractError::Conflict(format!(
            "{} is leased by live pid {}; another attempt is using this workspace",
            workspace.join(CONFIG_FILE).display(),
            record.owner_pid
        )));
    }
    restore(workspace, &record);
    Ok(true)
}

/// Put back the pre-lease config when the current file is exactly the lease's
/// generated content, then drop the record. A file edited since the lease was
/// taken belongs to the user and is left alone.
fn restore(workspace: &Path, record: &Record) {
    let config = workspace.join(CONFIG_FILE);
    if fs::read(&config).ok().as_deref() == Some(record.generated.as_bytes()) {
        let _ = match &record.previous {
            Some(previous) => fs::write(&config, previous),
            None => fs::remove_file(&config),
        };
    }
    let _ = fs::remove_file(workspace.join(LEASE_FILE));
}

fn write_record(workspace: &Path, record: &Record) -> Result<(), ContractError> {
    let body = json!({
        "owner_pid": record.owner_pid,
        "generated": record.generated,
        "previous": record.previous,
    })
    .to_string();
    let path = workspace.join(LEASE_FILE);
    let tmp = workspace.join(format!("{LEASE_FILE}.tmp"));
    fs::write(&tmp, body)
        .and_then(|()| fs::rename(&tmp, &path))
        .map_err(|e| {
            let _ = fs::remove_file(&tmp);
            ContractError::KnownFailure(format!("write lease {}: {e}", path.display()))
        })
}

fn read_record(workspace: &Path) -> Option<Record> {
    let text = fs::read_to_string(workspace.join(LEASE_FILE)).ok()?;
    let value: Value = serde_json::from_str(&text).ok()?;
    let owner_pid = u32::try_from(value.get("owner_pid")?.as_u64()?).ok()?;
    let generated = value.get("generated")?.as_str()?.to_string();
    let previous = match value.get("previous")? {
        Value::Null => None,
        Value::String(text) => Some(text.clone()),
        _ => return None,
    };
    Some(Record {
        owner_pid,
        generated,
        previous,
    })
}

/// Whether `pid` names a live process (`EPERM` counts as alive).
fn pid_alive(pid: u32) -> bool {
    if pid == 0 {
        return false;
    }
    match Command::new("/bin/kill")
        .arg("-0")
        .arg(pid.to_string())
        .output()
    {
        Ok(out) if out.status.success() => true,
        Ok(out) => String::from_utf8_lossy(&out.stderr).contains("Operation not permitted"),
        Err(_) => false,
    }
}

/// Add `names` to the workspace's local git excludes so the override never
/// enters a candidate commit. Per-clone and never committed; a workspace that
/// is not a git repo has no candidate commit, so a missing `.git` is fine.
fn exclude_locally(workspace: &Path, names: &[&str]) {
    let git = workspace.join(".git");
    if !git.is_dir() {
        return;
    }
    let exclude = git.join("info").join("exclude");
    if let Some(parent) = exclude.parent() {
        let _ = fs::create_dir_all(parent);
    }
    let mut text = fs::read_to_string(&exclude).unwrap_or_default();
    let mut changed = false;
    for name in names {
        if !text.lines().any(|line| line.trim() == *name) {
            if !text.is_empty() && !text.ends_with('\n') {
                text.push('\n');
            }
            text.push_str(name);
            text.push('\n');
            changed = true;
        }
    }
    if changed {
        let _ = fs::write(&exclude, text);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use agalma_testkit::ScratchDir;

    fn workspace(name: &str) -> ScratchDir {
        let dir = ScratchDir::new(&format!("provider-lease-{name}"));
        fs::create_dir_all(dir.join(".git").join("info")).expect("workspace");
        dir
    }

    /// A pid that just exited (pid reuse within the test window is negligible).
    fn dead_pid() -> u32 {
        let mut child = Command::new("/usr/bin/true").spawn().expect("spawn true");
        let pid = child.id();
        child.wait().expect("reap true");
        pid
    }

    fn set_owner(ws: &Path, pid: u32) {
        let mut record = read_record(ws).expect("record");
        record.owner_pid = pid;
        write_record(ws, &record).expect("rewrite record");
    }

    const GENERATED: &str =
        r#"{"provider":{"opencode-go":{"options":{"baseURL":"http://127.0.0.1:9999"}}}}"#;

    #[test]
    fn release_without_prior_config_removes_override_and_record() {
        let ws = workspace("fresh");
        let lease = acquire(&ws, GENERATED.to_string()).expect("acquire");
        assert_eq!(fs::read_to_string(ws.join(CONFIG_FILE)).unwrap(), GENERATED);
        assert!(ws.join(LEASE_FILE).exists(), "record written before config");
        lease.release();
        assert!(!ws.join(CONFIG_FILE).exists());
        assert!(!ws.join(LEASE_FILE).exists());
    }

    #[test]
    fn user_loopback_config_is_restored_byte_exact() {
        // Regression: a user's own local-model config also points at 127.0.0.1;
        // it must come back, never be classified as Agalma's and deleted.
        let ws = workspace("user-loopback");
        let user = br#"{"provider":{"ollama":{"options":{"baseURL":"http://127.0.0.1:11434"}}}}"#;
        fs::write(ws.join(CONFIG_FILE), user).unwrap();
        acquire(&ws, GENERATED.to_string())
            .expect("acquire")
            .release();
        assert_eq!(fs::read(ws.join(CONFIG_FILE)).unwrap(), user);
        assert!(!ws.join(LEASE_FILE).exists());
    }

    #[test]
    fn stale_lease_from_dead_owner_is_recovered() {
        // The SIGKILL case: the owner never released; the next launch restores.
        let ws = workspace("stale");
        let user = "{\"theme\":\"user\"}";
        fs::write(ws.join(CONFIG_FILE), user).unwrap();
        let leaked = acquire(&ws, GENERATED.to_string()).expect("acquire");
        std::mem::forget(leaked);
        set_owner(&ws, dead_pid());
        assert!(reconcile(&ws).expect("reconcile"), "stale lease recovered");
        assert_eq!(fs::read_to_string(ws.join(CONFIG_FILE)).unwrap(), user);
        assert!(!ws.join(LEASE_FILE).exists());
        assert!(
            !reconcile(&ws).expect("idempotent"),
            "nothing left to recover"
        );
    }

    #[test]
    fn stale_lease_keeps_a_config_edited_after_the_lease() {
        let ws = workspace("edited");
        std::mem::forget(acquire(&ws, GENERATED.to_string()).expect("acquire"));
        set_owner(&ws, dead_pid());
        fs::write(ws.join(CONFIG_FILE), "{\"edited\":true}").unwrap();
        assert!(reconcile(&ws).expect("reconcile"));
        assert_eq!(
            fs::read_to_string(ws.join(CONFIG_FILE)).unwrap(),
            "{\"edited\":true}",
            "a file that no longer matches the lease belongs to the user"
        );
        assert!(!ws.join(LEASE_FILE).exists());
    }

    #[test]
    fn live_owner_lease_is_a_conflict() {
        let ws = workspace("live");
        std::mem::forget(acquire(&ws, GENERATED.to_string()).expect("acquire"));
        let mut owner = Command::new("/bin/sleep").arg("30").spawn().expect("sleep");
        set_owner(&ws, owner.id());
        let err = acquire(&ws, GENERATED.to_string()).expect_err("must conflict");
        assert!(matches!(err, ContractError::Conflict(_)), "{err:?}");
        assert_eq!(
            fs::read_to_string(ws.join(CONFIG_FILE)).unwrap(),
            GENERATED,
            "the live owner's override is untouched"
        );
        let _ = owner.kill();
        let _ = owner.wait();
        assert!(reconcile(&ws).expect("owner gone, now stale"));
        assert!(!ws.join(CONFIG_FILE).exists());
    }

    #[test]
    fn malformed_record_is_dropped_without_touching_config() {
        let ws = workspace("malformed");
        fs::write(ws.join(CONFIG_FILE), "{\"user\":1}").unwrap();
        fs::write(ws.join(LEASE_FILE), "not json").unwrap();
        assert!(!reconcile(&ws).expect("reconcile"));
        assert_eq!(
            fs::read_to_string(ws.join(CONFIG_FILE)).unwrap(),
            "{\"user\":1}"
        );
        assert!(!ws.join(LEASE_FILE).exists());
    }

    #[test]
    fn release_ignores_a_record_taken_over_by_another_owner() {
        let ws = workspace("takeover");
        let lease = acquire(&ws, GENERATED.to_string()).expect("acquire");
        set_owner(&ws, dead_pid());
        let foreign = read_record(&ws).unwrap().owner_pid;
        lease.release();
        assert!(ws.join(CONFIG_FILE).exists(), "not ours to restore");
        assert_eq!(read_record(&ws).unwrap().owner_pid, foreign);
    }

    #[test]
    fn override_and_record_are_locally_excluded_once() {
        let ws = workspace("exclude");
        acquire(&ws, GENERATED.to_string())
            .expect("acquire")
            .release();
        acquire(&ws, GENERATED.to_string())
            .expect("acquire")
            .release();
        let exclude = fs::read_to_string(ws.join(".git/info/exclude")).unwrap();
        for name in [CONFIG_FILE, LEASE_FILE] {
            assert_eq!(
                exclude.lines().filter(|l| l.trim() == name).count(),
                1,
                "{name} excluded exactly once:\n{exclude}"
            );
        }
    }
}
