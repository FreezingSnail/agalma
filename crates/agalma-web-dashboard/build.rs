//! Deterministic compiled asset inventory for the dashboard package (WEB.4).
//!
//! The script watches only committed source inputs (`assets/` and this file),
//! never an `OUT_DIR` output. It emits one static table of
//! `(request_path, content_type, include_bytes!(...))` rows sorted by request
//! path, so adding a browser asset later requires no server-source or inventory
//! list edit.
//!
//! The walk itself lives in `src/asset_walk.rs` and is shared with runtime
//! tests; the same confinement rules therefore guard both sealing and testing.

include!("src/asset_walk.rs");

use std::env;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let manifest_dir = PathBuf::from(
        env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is always set by Cargo"),
    );
    let assets_root = manifest_dir.join("assets");
    println!("cargo:rerun-if-changed={}", assets_root.display());

    let assets = collect_assets(&assets_root)
        .unwrap_or_else(|error| panic!("compiled asset inventory: {error}"));

    let mut generated = String::new();
    generated.push_str("// @generated by build.rs; deterministic compiled asset inventory (WEB.4).\n");
    generated.push_str("// Source: committed files under `assets/`. Do not edit by hand.\n");
    generated.push_str("pub static DASHBOARD_ASSETS: &[(&str, &str, &[u8])] = &[\n");
    for asset in &assets {
        // Watch each committed source file explicitly; OUT_DIR is never an input.
        println!(
            "cargo:rerun-if-changed={}",
            assets_root.join(&asset.relative_path).display()
        );
        generated.push_str(&format!(
            "    ({:?}, {:?}, include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/{}\"))),\n",
            asset.request_path, asset.content_type, asset.relative_path
        ));
    }
    generated.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is always set by Cargo"));
    fs::write(out_dir.join("dashboard_assets.rs"), generated)
        .expect("write generated dashboard asset inventory");
}
